import { Router } from "express";
import type { Transaction } from "@retrest/shared";
import type { AppContext } from "../context.ts";
import { sendError } from "../lib/http.ts";
import { requireSession, sessionUser } from "../middleware/session.ts";
import { businessExportCsv, makePdf, receiptHtml } from "../services/documents.ts";

const MONTH_PATTERN = /^\d{4}-(0[1-9]|1[0-2])$/;

/** Business-expense exports and individual payment receipts (CSV, PDF, HTML). */
export function documentRoutes(context: AppContext) {
  const { db, config } = context;
  const router = Router();
  const session = requireSession(config);

  router.get("/export", session, (request, response) => {
    const userId = sessionUser(response);
    const month = typeof request.query.month === "string" ? request.query.month : new Date().toISOString().slice(0, 7);
    if (!MONTH_PATTERN.test(month)) return sendError(response, 400, "Invalid month");
    const rows = db
      .prepare(
        "SELECT t.* FROM transaction_logs t JOIN merchant_subscriptions s ON s.id=t.subscription_id WHERE t.user_id=? AND s.is_business_expense=1 AND t.status='APPROVED' AND substr(t.created_at,1,7)=? ORDER BY t.created_at DESC",
      )
      .all(userId, month) as unknown as Transaction[];

    if (request.query.format === "pdf") {
      const pdf = makePdf([
        "RETREST / BUSINESS EXPENSE RECEIPT PACK",
        `Statement month: ${month}`,
        `Generated: ${new Date().toISOString().slice(0, 10)}`,
        "",
        ...rows.flatMap((t) => [
          t.merchant_name,
          `${t.created_at.slice(0, 10)} | ${t.currency} ${(t.amount / 100).toFixed(2)} | APPROVED`,
          `Receipt: ${t.id}`,
          "",
        ]),
        `Total receipts: ${rows.length}`,
        "Generated from settled RETREST transactions. Demo environment.",
      ]);
      response
        .type("application/pdf")
        .attachment(`retrest-receipts-${month}.pdf`)
        .send(pdf);
      return;
    }
    response
      .type("text/csv; charset=utf-8")
      .attachment(`retrest-receipts-${month}.csv`)
      .send(businessExportCsv(rows));
  });

  router.get("/receipts/:id", session, (request, response) => {
    const userId = sessionUser(response);
    const id = String(request.params.id);
    const t = db
      .prepare("SELECT * FROM transaction_logs WHERE id=? AND user_id=? AND status='APPROVED'")
      .get(id, userId) as unknown as Transaction | undefined;
    if (!t) return sendError(response, 404, "Receipt not found");

    if (request.query.format === "pdf") {
      const pdf = makePdf([
        "RETREST / PAYMENT RECEIPT",
        "",
        t.merchant_name,
        `Amount: ${t.currency} ${(t.amount / 100).toFixed(2)}`,
        "Status: APPROVED",
        `Date: ${t.created_at}`,
        `Receipt ID: ${id}`,
        `FX conversion: NGN ${(t.fx_ngn_amount / 100).toFixed(2)}`,
        `Pool contribution: ${t.currency} ${(t.pool_amount / 100).toFixed(2)}`,
        "",
        "Demo environment. Automatically generated by RETREST.",
      ]);
      response.type("application/pdf").attachment(`retrest-receipt-${id}.pdf`).send(pdf);
      return;
    }
    response.type("text/html; charset=utf-8").send(receiptHtml(t));
  });

  return router;
}
